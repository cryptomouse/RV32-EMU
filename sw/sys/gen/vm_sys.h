
#if !defined(VM_SYS_H)
#define VM_SYS_H
#include <stddef.h>
#include <stdint.h>
#include <stdbool.h>
#define VM_SYS_RAM_START 0x10000000
#define VM_SYS_RAM_SIZE 0x00800000
// 8 MiB
#define VM_SYS_MMIO_START 0xF0000000UL
#define VM_SYS_MMIO_SIZE 0x01000000
#define VM_SYS_CONSOLE_MMIOADR (VM_SYS_MMIO_START | 0x10)
#define VM_SYS_CONSOLE_PRINT_CHAR8_ADR (VM_SYS_CONSOLE_MMIOADR | 0x00)
#define VM_SYS_CONSOLE_SCAN_CHAR8_ADR (VM_SYS_CONSOLE_MMIOADR | 0x01)
#define VM_SYS_CONSOLE_PRINT_INT32_ADR (VM_SYS_CONSOLE_MMIOADR | 0x10)
#define VM_SYS_CONSOLE_PRINT_UINT32_ADR (VM_SYS_CONSOLE_MMIOADR | 0x14)
#define VM_SYS_CONSOLE_PRINT_INT32_HEX_ADR (VM_SYS_CONSOLE_MMIOADR | 0x18)
#define VM_SYS_CONSOLE_PRINT_UINT32_HEX_ADR (VM_SYS_CONSOLE_MMIOADR | 0x1C)
#define VM_SYS_DISPLAY_MMIOADR (VM_SYS_MMIO_START | 0x1000)
#define VM_SYS_DISPLAY_CR (VM_SYS_DISPLAY_MMIOADR | 0x00)
#define VM_SYS_DISPLAY_SR (VM_SYS_DISPLAY_MMIOADR | 0x04)
#define VM_SYS_DISPLAY_ER (VM_SYS_DISPLAY_MMIOADR | 0x08)
#define VM_SYS_DISPLAY_WIDTH (VM_SYS_DISPLAY_MMIOADR | 0x0C)
#define VM_SYS_DISPLAY_HEIGHT (VM_SYS_DISPLAY_MMIOADR | 0x10)
#define VM_SYS_DISPLAY_FB (VM_SYS_DISPLAY_MMIOADR | 0x14)
#define VM_SYS_DISPLAY_REFRESH (VM_SYS_DISPLAY_MMIOADR | 0x18)
#define VM_SYS_DISPLAY_FRAME_COUNTER (VM_SYS_DISPLAY_MMIOADR | 0x1C)
// frames shown since EN
#define VM_SYS_DISPLAY_CR_EN 0x1
#define VM_SYS_DISPLAY_SR_ON 0x1
#define VM_SYS_DISPLAY_SR_ERR 0x2
#define VM_SYS_DISPLAY_ER_WIDTH 0x1
#define VM_SYS_DISPLAY_ER_HEIGHT 0x2
#define VM_SYS_DISPLAY_ER_FB 0x4

__attribute__((always_inline))
inline volatile uint32_t *vm_sys_reg(uint32_t adr) {
	return (volatile uint32_t *)adr;
}
#endif

